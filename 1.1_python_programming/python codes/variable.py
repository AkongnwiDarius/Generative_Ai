# variable naming convention

# camel casing
myModel = 'data'
print(myModel)

# snake casing
user_name = 'kincaid'
print(user_name)

# pascal casing
MyName = 'faith'
print(MyName)

# things to avoid in variable naming condition
# never start naming your variable with a number e.g 2age
# never use a dash to seperate words in a variable e.g model-train
# never use key words to name a variable i.e words that are lnbuilt in python

